import { test, expect } from "@playwright/test";
import { start, jump, join, next } from "./helpers";
test("three teams pitch, edit private ratings, recover saves, reveal bonuses and reach the video", async ({ page, browser }) => {
  const code = await start(page), contexts = await Promise.all([320, 390, 430, 390].map(width => browser.newContext({ viewport: { width, height: 844 } })));
  const phones = await Promise.all(contexts.map(c => c.newPage()));
  try {
    for (let i = 0; i < 3; i++) await join(phones[i], code, ["Alice", "Bilal", "Camille"][i]);
    await jump(page, 9, "pitch");
    await page.getByRole("button", { name: "Alice, sans équipe", exact: true }).click();
    await page.getByRole("button", { name: "Choisir l’équipe 2", exact: true }).click();
    await page.getByRole("button", { name: "Bilal, sans équipe", exact: true }).click();
    await page.getByRole("button", { name: "Choisir l’équipe 3", exact: true }).click();
    await page.getByRole("button", { name: "Camille, sans équipe", exact: true }).click();
    await page.getByRole("button", { name: "Vérifier les équipes", exact: true }).click();
    await page.getByRole("button", { name: "Équipe 2", exact: true }).click();
    await page.getByRole("button", { name: "Alice, équipe 1", exact: true }).click();
    await expect(page.getByRole("button", { name: "Confirmer les équipes", exact: true })).toBeDisabled();
    await page.getByRole("button", { name: "Équipe 1", exact: true }).click();
    await page.getByRole("button", { name: "Alice, équipe 2", exact: true }).click();
    await page.reload();
    await expect(page.getByRole("button", { name: "Confirmer les équipes", exact: true })).toBeEnabled({ timeout: 13000 });
    await page.screenshot({ path: "artifacts/pitch-teams.png", animations: "disabled" });
    await page.getByRole("button", { name: "Confirmer les équipes", exact: true }).click();
    await phones[3].goto(`/join/${code}`); await phones[3].getByLabel("Comment vous appelle-t-on ?").fill("Public tardif"); await phones[3].getByRole("button", { name: "J’entre dans la partie" }).click();
    await expect(phones[3].getByText("VOUS ÊTES DANS LE PUBLIC", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Commencer le pitch de l’équipe 1", exact: true }).click();
    await page.keyboard.press("ArrowRight"); await expect(page.locator(".stage-canvas")).toHaveAttribute("data-beat", "pitch");
    await page.getByRole("button", { name: "Ouvrir le vote pour l’équipe 1", exact: true }).click();
    await expect(phones[0].getByText("C’est votre équipe : vous ne pouvez pas la noter.", { exact: true })).toBeVisible();
    let fail = true;
    await phones[1].route(`**/api/rooms/${code}`, async route => { if (route.request().method() === "POST" && route.request().postDataJSON().action === "rate-pitch" && fail) { fail = false; await route.abort(); } else await route.continue(); });
    await phones[1].getByRole("button", { name: "Note 4 sur 10", exact: true }).click();
    await phones[1].getByRole("button", { name: "Réessayer la note", exact: true }).click();
    await expect(phones[1].getByText("Note 4/10 enregistrée.", { exact: true })).toBeVisible();
    await phones[1].getByRole("button", { name: "Note 6 sur 10", exact: true }).click();
    await expect(phones[1].getByText("Note 6/10 enregistrée.", { exact: true })).toBeVisible();
    await phones[1].reload(); await expect(phones[1].getByRole("button", { name: "Note 6 sur 10", exact: true })).toHaveAttribute("aria-pressed", "true");
    await phones[2].getByRole("button", { name: "Note 8 sur 10", exact: true }).click();
    await phones[3].getByRole("button", { name: "Note 7 sur 10", exact: true }).click();
    await expect(page.getByText("Vote ouvert · 3 réponse(s)", { exact: true })).toBeVisible();
    await expect(page.locator(".pitch-average")).toHaveCount(0);
    const privateState = await phones[0].evaluate(async c => (await fetch(`/api/rooms/${c}`)).json(), code);
    expect(privateState.pitch.teams[0].average).toBeUndefined(); expect(privateState.xp).toBe(0);
    await phones[1].screenshot({ path: "artifacts/pitch-vote-390.png", fullPage: true });
    await page.getByRole("button", { name: "Fermer le vote", exact: true }).click();
    await page.getByRole("button", { name: "Commencer le pitch de l’équipe 2", exact: true }).click();
    await page.getByRole("button", { name: "Ouvrir le vote pour l’équipe 2", exact: true }).click();
    for (const i of [0, 2, 3]) await phones[i].getByRole("button", { name: "Note 10 sur 10", exact: true }).click();
    await expect(page.getByText("Vote ouvert · 3 réponse(s)", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Fermer le vote", exact: true }).click();
    await page.getByRole("button", { name: "Commencer le pitch de l’équipe 3", exact: true }).click();
    await page.getByRole("button", { name: "Ouvrir le vote pour l’équipe 3", exact: true }).click();
    for (const viewport of [{ width: 1024, height: 768 }, { width: 1366, height: 768 }, { width: 1920, height: 1080 }]) {
      await page.setViewportSize(viewport); expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await expect(page.getByRole("button", { name: "Fermer le vote", exact: true })).toBeInViewport();
    }
    expect(await phones[0].evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await phones[0].screenshot({ path: "artifacts/pitch-vote-320.png", fullPage: true });
    await page.getByRole("button", { name: "Fermer le vote", exact: true }).click();
    await expect(page.locator(".pitch-average")).toHaveCount(0);
    await page.getByRole("button", { name: "Révéler les résultats", exact: true }).click();
    await expect(page.locator(".team-1 .pitch-average")).toHaveText("7,0/10");
    await expect(page.locator(".team-2 .pitch-average")).toHaveText("10,0/10");
    await expect(page.locator(".team-3 .pitch-average")).toHaveText("Aucun vote");
    await expect(phones[0].locator(".student-player-strip")).toContainText("4900 points");
    await expect(phones[1].locator(".student-player-strip")).toContainText("7000 points");
    await expect(phones[3].locator(".student-player-strip")).toContainText("0 points");
    await page.screenshot({ path: "artifacts/pitch-results.png", animations: "disabled" });
    await page.reload(); await expect(page.locator(".team-1 .pitch-average")).toHaveText("7,0/10");
    await next(page, "pitch-leaderboard"); await expect(page.locator(".ranking-top")).toContainText("Bilal");
    await next(page, "instadeep-teaser"); await expect(page.locator(".tunisian-teaser")).toContainText("680 millions de dollars");
    await next(page, "instadeep-reveal"); await expect(page.locator(".instadeep-layout")).toContainText("InstaDeep : une startup tunisienne, trois façons d’entreprendre");
    await expect(phones[0].locator(".student-player-strip")).toContainText("4900 points");
    await next(page, "conclusion"); await expect(page.locator("video")).toBeVisible();
  } finally { for (const c of contexts) await c.close(); }
});
